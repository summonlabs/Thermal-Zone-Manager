// Benchmark: completed evaluation operations.
//
// Every number printed here is measured with std::chrono::steady_clock around
// operations that ran to completion. An iteration that is refused is not
// counted, and no timing is estimated, cached or hard-coded. Submission
// latency is deliberately not measured: what is timed is the work the library
// finished.
//
// The facility data is generated by this harness, so the workload is labelled
// SYNTHETIC. It says nothing about real plant hardware.
//
// usage: benchmark_evaluation [--quick | --full] [--zones <n>] [--edges <n>]
//                             [--iterations <n>] [--store <dir>]

#include <thermal_zone_manager/thermal_zone_manager.hpp>

#include <charconv>
#include <chrono>
#include <cstdint>
#include <iostream>
#include <memory>
#include <string>
#include <system_error>
#include <utility>
#include <vector>

namespace tzm = thermal_zone_manager;

namespace {

constexpr std::int64_t kFloorMc = 15000;
constexpr std::int64_t kDerateOnsetMc = 70000;
constexpr std::int64_t kCeilingMc = 90000;
constexpr std::int64_t kCriticalMc = 100000;
constexpr std::int64_t kResistanceUkw = 400000;
constexpr std::int64_t kDeclaredHeatMw = 20000;
constexpr std::int64_t kBaseTemperatureMc = 45000;
constexpr std::int64_t kTemperatureStepMc = 100;
constexpr std::int64_t kValidityNs = 60000000000LL;
constexpr const char* kDefaultStore = "tzm-benchmark-store";
constexpr int kEphemeralWarmup = 2;
constexpr int kDurableWarmup = 1;

struct Options {
  std::size_t zones = 256;
  std::size_t edges = 512;
  std::size_t iterations = 100;
  std::string store = kDefaultStore;
};

struct Facility {
  std::vector<tzm::ZoneConfiguration> zones;
  std::vector<tzm::CouplingEdge> coupling;
  std::size_t edge_count = 0;
};

struct Timing {
  std::size_t completed = 0;
  std::int64_t total_ns = 0;
};

struct Ids {
  std::uint64_t command = 1;
  std::uint64_t attempt = 1;
  std::uint64_t evaluation = 1;
};

bool parse_size(const std::string& text, std::size_t& out) {
  if (text.empty()) {
    return false;
  }
  std::size_t value = 0;
  const std::from_chars_result result =
      std::from_chars(text.data(), text.data() + text.size(), value);
  if (result.ec != std::errc() || result.ptr != text.data() + text.size()) {
    return false;
  }
  out = value;
  return true;
}

// Fills in the workload defaults for whichever values the caller did not give
// explicitly. Returns false for anything unusable; the caller exits 2.
bool parse_options(int argc, char** argv, Options& options) {
  bool quick = false;
  bool zones_given = false;
  bool edges_given = false;
  bool iterations_given = false;

  for (int index = 1; index < argc; ++index) {
    const std::string argument = argv[index];
    if (argument == "--quick") {
      quick = true;
    } else if (argument == "--full") {
      quick = false;
    } else if (argument == "--zones" || argument == "--edges" || argument == "--iterations" ||
               argument == "--store") {
      if (index + 1 >= argc) {
        std::cerr << argument << " requires a value\n";
        return false;
      }
      const std::string value = argv[++index];
      if (argument == "--store") {
        if (value.empty()) {
          std::cerr << "--store requires a directory\n";
          return false;
        }
        options.store = value;
      } else {
        std::size_t parsed = 0;
        if (!parse_size(value, parsed)) {
          std::cerr << argument << " requires a non-negative integer\n";
          return false;
        }
        if (argument == "--zones") {
          options.zones = parsed;
          zones_given = true;
        } else if (argument == "--edges") {
          options.edges = parsed;
          edges_given = true;
        } else {
          options.iterations = parsed;
          iterations_given = true;
        }
      }
    } else {
      std::cerr << "unknown option: " << argument << "\n";
      return false;
    }
  }

  if (!zones_given) {
    options.zones = quick ? 16 : 256;
  }
  if (!edges_given) {
    options.edges = options.zones * 2;
  }
  if (!iterations_given) {
    options.iterations = quick ? 16 : 100;
  }

  if (options.zones < 3) {
    std::cerr << "--zones must be at least 3 so that the ring has no self coupling\n";
    return false;
  }
  if (options.zones > tzm::kMaxZones) {
    std::cerr << "--zones exceeds the zone ceiling of " << tzm::kMaxZones << "\n";
    return false;
  }
  const std::size_t maximum_edges = options.zones * (options.zones - 1);
  if (options.edges < options.zones || options.edges > maximum_edges ||
      options.edges > tzm::kMaxCouplingEdges) {
    std::cerr << "--edges must be between " << options.zones << " and "
              << (maximum_edges < tzm::kMaxCouplingEdges ? maximum_edges : tzm::kMaxCouplingEdges)
              << " for " << options.zones << " zone(s)\n";
    return false;
  }
  if (options.iterations == 0) {
    std::cerr << "--iterations must be at least 1\n";
    return false;
  }
  return true;
}

// A deterministic graph: a ring (zone i to zone i+1) followed by skip edges,
// all carrying one fixed coefficient that keeps every zone inside the outgoing
// coupling budget. The zone graph is identical on every run and for every
// iteration count.
Facility build_facility(const Options& options) {
  Facility facility;
  for (std::size_t id = 1; id <= options.zones; ++id) {
    tzm::ZoneConfiguration zone;
    zone.id = tzm::ZoneId::from_value(id);
    zone.name = tzm::ZoneName::literal("bench-zone-" + std::to_string(id));
    zone.envelope.floor_temp = tzm::MilliCelsius{kFloorMc};
    zone.envelope.derate_onset = tzm::MilliCelsius{kDerateOnsetMc};
    zone.envelope.ceiling_temp = tzm::MilliCelsius{kCeilingMc};
    zone.envelope.critical_temp = tzm::MilliCelsius{kCriticalMc};
    zone.declared_heat = tzm::MilliWatts{kDeclaredHeatMw};
    zone.thermal_resistance = tzm::MicroKelvinPerWatt{kResistanceUkw};
    facility.zones.push_back(zone);
  }

  const std::size_t max_out_degree = (options.edges + options.zones - 1) / options.zones;
  const std::int32_t coefficient = static_cast<std::int32_t>(
      tzm::kMaxOutgoingCouplingPpm / static_cast<std::int64_t>(max_out_degree));

  for (std::size_t offset = 1; offset < options.zones && facility.edge_count < options.edges;
       ++offset) {
    for (std::size_t id = 1; id <= options.zones && facility.edge_count < options.edges; ++id) {
      tzm::CouplingEdge edge;
      edge.source = tzm::ZoneId::from_value(id);
      edge.sink = tzm::ZoneId::from_value(((id - 1 + offset) % options.zones) + 1);
      edge.coefficient = tzm::PartsPerMillion{coefficient};
      facility.coupling.push_back(edge);
      ++facility.edge_count;
    }
  }
  return facility;
}

bool ensure_epoch(tzm::ThermalZoneEngine& engine, std::uint64_t command_value,
                  tzm::ControlPlaneEpoch& epoch_out) {
  const tzm::FencingState fencing = engine.fencing();
  if (!fencing.epoch.is_zero()) {
    epoch_out = fencing.epoch;
    return true;
  }
  tzm::EpochRequest request;
  request.command = tzm::CommandId::from_value(command_value);
  request.attempt = tzm::AttemptId::first();
  request.expected_current = tzm::ControlPlaneEpoch::zero();
  request.target = tzm::ControlPlaneEpoch::first();
  const tzm::Result<tzm::EpochReceipt> receipt = engine.advance_epoch(request);
  if (!receipt.ok()) {
    std::cerr << receipt.error().to_string() << "\n";
    return false;
  }
  epoch_out = receipt.value().current;
  return true;
}

tzm::ObservationSequence next_sequence(const tzm::ThermalZoneEngine& engine, tzm::ZoneId zone) {
  const tzm::ZoneEvidence held = engine.evidence_for(zone);
  if (held.present) {
    return held.observation.sequence.next();
  }
  return tzm::ObservationSequence::first();
}

// Declares the facility and gives every zone one fresh synthetic observation.
bool prepare(tzm::ThermalZoneEngine& engine, const Facility& facility, tzm::ControlPlaneEpoch epoch,
             Ids& ids, tzm::Configuration& configuration_out) {
  tzm::ConfigurationRequest declaration;
  declaration.command = tzm::CommandId::from_value(ids.command++);
  declaration.attempt = tzm::AttemptId::from_value(ids.attempt++);
  declaration.epoch = epoch;
  declaration.expected_generation = engine.configuration().generation();
  declaration.zones = facility.zones;
  declaration.coupling = facility.coupling;
  declaration.policy.coupling_hops = 1;
  declaration.policy.release_hold_observations = 3;

  const tzm::Result<tzm::ConfigurationReceipt> applied = engine.apply_configuration(declaration);
  if (!applied.ok()) {
    std::cerr << applied.error().to_string() << "\n";
    return false;
  }

  const tzm::Configuration configuration = engine.configuration();
  const tzm::Timestamp now = engine.clock().now();
  for (std::size_t index = 0; index < configuration.zones().size(); ++index) {
    const tzm::ZoneConfiguration& zone = configuration.zones()[index];
    tzm::TemperatureObservation observation;
    observation.zone = zone.id;
    observation.zone_generation = zone.generation;
    observation.evidence_generation = configuration.evidence_generation();
    observation.sequence = next_sequence(engine, zone.id);
    observation.temperature = tzm::MilliCelsius{
        kBaseTemperatureMc + kTemperatureStepMc * static_cast<std::int64_t>(index)};
    observation.source = tzm::SourceId::literal("synthetic-benchmark-harness");
    observation.provenance = tzm::ProvenanceKind::SyntheticHarness;
    observation.observed_at = now;
    observation.validity = tzm::Nanoseconds{kValidityNs};
    observation.publisher_epoch = epoch;
    observation.publisher_incarnation = engine.incarnation();
    const tzm::Result<tzm::ObservationReceipt> ingested = engine.ingest_observation(observation);
    if (!ingested.ok()) {
      std::cerr << ingested.error().to_string() << "\n";
      return false;
    }
  }
  configuration_out = configuration;
  return true;
}

std::int64_t elapsed_ns(std::chrono::steady_clock::time_point start,
                        std::chrono::steady_clock::time_point end) {
  return std::chrono::duration_cast<std::chrono::nanoseconds>(end - start).count();
}

// (a) one evaluate() over every declared zone, on an ephemeral engine.
bool benchmark_evaluate(const Options& options, const Facility& facility, Timing& timing) {
  tzm::EngineOptions engine_options;
  engine_options.actor = tzm::ActorId::literal("tzm-benchmark-evaluate");

  tzm::Result<std::unique_ptr<tzm::ThermalZoneEngine>> opened =
      tzm::ThermalZoneEngine::open(engine_options);
  if (!opened.ok()) {
    std::cerr << opened.error().to_string() << "\n";
    return false;
  }
  const std::unique_ptr<tzm::ThermalZoneEngine> engine = std::move(opened.value());

  tzm::ControlPlaneEpoch epoch;
  if (!ensure_epoch(*engine, 1, epoch)) {
    return false;
  }
  Ids ids;
  ids.command = engine->fencing().revision.raw() + 1;
  ids.evaluation = ids.command;

  tzm::Configuration configuration;
  if (!prepare(*engine, facility, epoch, ids, configuration)) {
    return false;
  }

  const auto evaluate_once = [&engine, &configuration, &epoch, &ids]() {
    tzm::EvaluationRequest request;
    request.id = tzm::EvaluationId::from_value(ids.evaluation++);
    request.epoch = epoch;
    request.configuration_generation = configuration.generation();
    request.evidence_generation = configuration.evidence_generation();
    return engine->evaluate(request).ok();
  };

  for (int index = 0; index < kEphemeralWarmup; ++index) {
    if (!evaluate_once()) {
      std::cerr << "the warm-up evaluation was refused\n";
      return false;
    }
  }

  const auto start = std::chrono::steady_clock::now();
  for (std::size_t iteration = 0; iteration < options.iterations; ++iteration) {
    if (!evaluate_once()) {
      std::cerr << "an evaluation was refused during measurement\n";
      return false;
    }
    ++timing.completed;
  }
  const auto end = std::chrono::steady_clock::now();
  timing.total_ns = elapsed_ns(start, end);
  return true;
}

// (b) one evaluate() plus one commit_evaluation() per iteration, against a
//     durable store.
bool benchmark_evaluate_and_commit(const Options& options, const Facility& facility, Timing& timing) {
  tzm::EngineOptions engine_options;
  engine_options.root = options.store;
  engine_options.access = tzm::StoreAccess::ReadWrite;
  engine_options.create_if_missing = true;
  engine_options.actor = tzm::ActorId::literal("tzm-benchmark-commit");

  tzm::Result<std::unique_ptr<tzm::ThermalZoneEngine>> opened =
      tzm::ThermalZoneEngine::open(engine_options);
  if (!opened.ok()) {
    std::cerr << opened.error().to_string() << "\n";
    return false;
  }
  const std::unique_ptr<tzm::ThermalZoneEngine> engine = std::move(opened.value());

  tzm::ControlPlaneEpoch epoch;
  if (!ensure_epoch(*engine, 1, epoch)) {
    return false;
  }
  Ids ids;
  ids.command = engine->fencing().revision.raw() + 1;
  ids.evaluation = ids.command;

  tzm::Configuration configuration;
  if (!prepare(*engine, facility, epoch, ids, configuration)) {
    return false;
  }

  const auto evaluate_and_commit_once = [&engine, &configuration, &epoch, &ids]() {
    tzm::EvaluationRequest request;
    request.id = tzm::EvaluationId::from_value(ids.evaluation++);
    request.epoch = epoch;
    request.configuration_generation = configuration.generation();
    request.evidence_generation = configuration.evidence_generation();

    const tzm::Result<tzm::EvaluationResult> evaluated = engine->evaluate(request);
    if (!evaluated.ok()) {
      return false;
    }
    tzm::EvaluationCommitRequest commit;
    commit.command = tzm::CommandId::from_value(ids.command++);
    commit.attempt = tzm::AttemptId::from_value(ids.attempt++);
    commit.epoch = epoch;
    commit.evaluation = evaluated.value().id();
    commit.configuration_generation = evaluated.value().configuration_generation();
    commit.evidence_generation = evaluated.value().evidence_generation();
    commit.basis_revision = evaluated.value().basis_revision();
    const tzm::Result<tzm::EvaluationCommitReceipt> committed = engine->commit_evaluation(commit);
    return committed.ok();
  };

  for (int index = 0; index < kDurableWarmup; ++index) {
    if (!evaluate_and_commit_once()) {
      std::cerr << "the warm-up evaluation commit was refused\n";
      return false;
    }
  }

  const auto start = std::chrono::steady_clock::now();
  for (std::size_t iteration = 0; iteration < options.iterations; ++iteration) {
    if (!evaluate_and_commit_once()) {
      std::cerr << "an evaluation commit was refused during measurement\n";
      return false;
    }
    ++timing.completed;
  }
  const auto end = std::chrono::steady_clock::now();
  timing.total_ns = elapsed_ns(start, end);
  return true;
}

void report(const char* name, const Options& options, const Facility& facility,
            const Timing& timing) {
  const std::int64_t ns_per_op =
      timing.completed == 0 ? 0 : timing.total_ns / static_cast<std::int64_t>(timing.completed);
  std::cout << "  " << name << ": iterations " << timing.completed << ", total " << timing.total_ns
            << " ns, " << tzm::format_milli(ns_per_op) << " us/op, workload SYNTHETIC\n";
  std::cout << "benchmark " << name << " zones=" << options.zones << " edges=" << facility.edge_count
            << " iterations=" << timing.completed << " total_ns=" << timing.total_ns
            << " ns_per_op=" << ns_per_op << " workload=SYNTHETIC\n";
}

}  // namespace

int main(int argc, char** argv) {
  Options options;
  if (!parse_options(argc, argv, options)) {
    return 2;
  }

  const Facility facility = build_facility(options);

  std::cout << "benchmark: evaluate and evaluate+commit, Thermal Zone Manager\n";
  std::cout << "  workload: SYNTHETIC (generated facility data, no real hardware is exercised)\n";
  std::cout << "  zones " << options.zones << ", edges " << facility.edge_count << ", iterations "
            << options.iterations << ", store " << options.store << "\n";
  std::cout << "  timing: std::chrono::steady_clock around completed operations only\n";

  Timing evaluate_timing;
  if (!benchmark_evaluate(options, facility, evaluate_timing)) {
    std::cerr << "the evaluate benchmark did not complete\n";
    return 1;
  }
  report("evaluate_zones", options, facility, evaluate_timing);

  Timing commit_timing;
  if (!benchmark_evaluate_and_commit(options, facility, commit_timing)) {
    std::cerr << "the evaluate+commit benchmark did not complete\n";
    return 1;
  }
  report("evaluate_and_commit", options, facility, commit_timing);

  return 0;
}
